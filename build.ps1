param([switch]$SkipTests,[switch]$ReuseBuiltUi,[switch]$Portable,[string]$OutputDirectory)
$ErrorActionPreference='Stop'
$taskProject=Join-Path $PSScriptRoot 'src/CursorMotion.csproj'
$taskDesktop=Join-Path $PSScriptRoot 'desktop'
$taskRuntime=Join-Path $taskDesktop 'vendor/electron'
if(-not(Test-Path -LiteralPath (Join-Path $taskRuntime 'electron.exe'))){throw 'Electron runtime missing: unpack verified electron-v45.0.0-win32-x64.zip into desktop/vendor/electron first.'}
dotnet build $taskProject -c Release --nologo
if($LASTEXITCODE -ne 0){throw 'Native build failed'}
$taskEngine=Join-Path $PSScriptRoot 'src/bin/Release/net10.0-windows/CursorMotion.Engine.exe'
function Invoke-Engine([string]$taskArguments){
 $taskProcess=Start-Process -FilePath $taskEngine -ArgumentList $taskArguments -PassThru -WindowStyle Hidden
 $taskProcess.WaitForExit();if($taskProcess.ExitCode -ne 0){throw "Engine failed: $taskArguments"}
}
Invoke-Engine ('--compile-shaders --offscreen --output "'+(Join-Path $PSScriptRoot 'src/Assets')+'"')
dotnet build $taskProject -c Release --nologo
if($LASTEXITCODE -ne 0){throw 'Shader embed build failed'}
if($ReuseBuiltUi){
 $taskProof=Join-Path $taskDesktop 'ui/assets/settings/native-artwork-provenance.json'
 $taskShader=[IO.File]::ReadAllText((Join-Path $PSScriptRoot 'src/Cursor.hlsl'))
 $taskShaderHash=[Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($taskShader)))
 if(-not(Test-Path -LiteralPath $taskProof) -or (Get-Content -Raw -LiteralPath $taskProof|ConvertFrom-Json).shaderSha256 -ne $taskShaderHash){throw 'Built UI artwork is stale; rebuild UI from the current native renderer'}
 $taskCurrentProof=Join-Path $PSScriptRoot 'src/obj/artwork-fingerprint.json'
 Invoke-Engine ('--artwork-fingerprint --offscreen --output "'+$taskCurrentProof+'"')
 if((Get-Content -Raw -LiteralPath $taskProof|ConvertFrom-Json).paletteSha256 -ne (Get-Content -Raw -LiteralPath $taskCurrentProof|ConvertFrom-Json).paletteSha256){throw 'Built UI palette images are stale; rebuild native artwork and UI'}
}else{
 Invoke-Engine ('--export-native-art --offscreen --output "'+(Join-Path $taskDesktop 'renderer/public/assets/settings')+'"')
 $taskMetadata=Get-Content -Raw -LiteralPath (Join-Path $taskDesktop 'renderer/public/assets/settings/native-artwork-metadata.json')
 Set-Content -LiteralPath (Join-Path $taskDesktop 'renderer/src/native-artwork-meta.mjs') -Value ('// Generated by NativeArtwork.Export from the production GPU renderer.'+[Environment]::NewLine+'export const nativeArtworkMetadata = '+$taskMetadata+';') -Encoding utf8
}
if($ReuseBuiltUi){if(-not(Test-Path -LiteralPath (Join-Path $taskDesktop 'ui/index.html'))){throw 'ReuseBuiltUi requires an existing desktop/ui build'}}else{
Push-Location (Join-Path $taskDesktop 'renderer')
try {
 if(-not(Test-Path 'node_modules/vite/bin/vite.js')){npm ci --no-audit --no-fund;if($LASTEXITCODE -ne 0){throw 'Renderer dependencies failed'}}
 if(-not $SkipTests){npm test;if($LASTEXITCODE -ne 0){throw 'Renderer tests failed'}}
 npm run build
 if($LASTEXITCODE -ne 0){throw 'Renderer build failed'}
} finally {Pop-Location}
}
if(-not $SkipTests){Invoke-Engine ('--self-test --offscreen --output "'+(Join-Path $PSScriptRoot 'test-v3-native')+'"')}
$taskDist=if($OutputDirectory){[IO.Path]::GetFullPath($OutputDirectory)}else{Join-Path $PSScriptRoot 'dist/CursorMotion-v3.0'}
$taskStudio=Join-Path $taskDist 'studio'
$taskApp=Join-Path $taskStudio 'resources/app'
New-Item -ItemType Directory -Force -Path $taskApp | Out-Null
Get-ChildItem -LiteralPath $taskRuntime | Where-Object Name -ne 'electron.exe' | ForEach-Object {Copy-Item -LiteralPath $_.FullName -Destination $taskStudio -Recurse -Force}
Copy-Item -LiteralPath (Join-Path $taskRuntime 'electron.exe') -Destination (Join-Path $taskStudio 'CursorMotion.Studio.exe') -Force
foreach($taskFile in @('main.cjs','preload.cjs','package.json')){Copy-Item -LiteralPath (Join-Path $taskDesktop $taskFile) -Destination $taskApp -Force}
$taskUiTarget=[IO.Path]::GetFullPath((Join-Path $taskApp 'ui'))
$taskAppPrefix=[IO.Path]::GetFullPath($taskApp)+[IO.Path]::DirectorySeparatorChar
if(-not $taskUiTarget.StartsWith($taskAppPrefix,[StringComparison]::OrdinalIgnoreCase)){throw 'Unsafe UI output path'}
if(Test-Path -LiteralPath $taskUiTarget){
 if((Get-Item -LiteralPath $taskUiTarget).Attributes -band [IO.FileAttributes]::ReparsePoint){throw 'UI output must not be a link'}
 Remove-Item -LiteralPath $taskUiTarget -Recurse -Force
}
Copy-Item -LiteralPath (Join-Path $taskDesktop 'ui') -Destination $taskApp -Recurse -Force
dotnet publish $taskProject -c Release -r win-x64 --self-contained true -p:PublishSingleFile=false -o $taskDist --nologo
if($LASTEXITCODE -ne 0){throw 'Native publish failed'}
Copy-Item -LiteralPath (Join-Path $taskDist 'CursorMotion.Engine.exe') -Destination (Join-Path $taskDist 'CursorMotion.exe') -Force
& (Join-Path $taskDesktop 'brand-exe.ps1') -Executable (Join-Path $taskStudio 'CursorMotion.Studio.exe') -Icon (Join-Path $taskDesktop 'ui/assets/AppIcon.ico')
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'README.md'),(Join-Path $PSScriptRoot 'LICENSE'),(Join-Path $PSScriptRoot 'THIRD-PARTY-NOTICES.txt'),(Join-Path $PSScriptRoot 'ORIGINAL-LICENSE.txt') -Destination $taskDist -Force
Copy-Item -LiteralPath (Join-Path $taskDesktop 'RESTORE-CURSOR.cmd') -Destination $taskDist -Force
if($Portable){
 Get-ChildItem -LiteralPath (Join-Path $taskDesktop 'portable') -File | ForEach-Object {Copy-Item -LiteralPath $_.FullName -Destination $taskDist -Force}
 New-Item -ItemType Directory -Path (Join-Path $taskDist 'data') -Force | Out-Null
 Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'src/Assets/AppIcon.ico'),(Join-Path $PSScriptRoot 'docs/native-custom-portable.md') -Destination $taskDist -Force
}
$taskDependencies=Get-Content -Raw (Join-Path $taskDist 'CursorMotion.Engine.deps.json') | ConvertFrom-Json
$taskAssets=Get-Content -Raw (Join-Path $PSScriptRoot 'src/obj/project.assets.json') | ConvertFrom-Json
$taskPackageRoot=$taskAssets.packageFolders.PSObject.Properties.Name | Select-Object -First 1
foreach($taskPackage in @('Microsoft.NETCore.App.Runtime.win-x64','Microsoft.WindowsDesktop.App.Runtime.win-x64')){
 $taskLibrary=$taskDependencies.libraries.PSObject.Properties.Name | Where-Object {$_ -like "runtimepack.$taskPackage/*"} | Select-Object -First 1
 if(-not $taskLibrary){throw "Missing runtime package identity: $taskPackage"}
 $taskVersion=$taskLibrary.Split('/')[1]
 $taskLicenseSource=Join-Path $taskPackageRoot ($taskPackage.ToLowerInvariant()+'/'+$taskVersion)
 $taskLicenseTarget=Join-Path $taskDist ('licenses/'+$taskPackage)
 New-Item -ItemType Directory -Path $taskLicenseTarget -Force | Out-Null
 $taskLicenses=@(Get-ChildItem -LiteralPath $taskLicenseSource -Force -File | Where-Object {$_.Name -match '^(LICENSE(\.TXT)?|THIRD-PARTY-NOTICES\.TXT)$'})
 if($taskLicenses.Count -eq 0){throw "Runtime license missing: $taskPackage"}
 $taskLicenses | ForEach-Object {Copy-Item -LiteralPath $_.FullName -Destination $taskLicenseTarget -Force}
}
if(-not $SkipTests){
 $taskUi=Start-Process -FilePath (Join-Path $taskStudio 'CursorMotion.Studio.exe') -ArgumentList ('--ui-test --engine "'+(Join-Path $taskDist 'CursorMotion.Engine.exe')+'" --output "'+(Join-Path $PSScriptRoot 'test-v3-ui')+'"') -PassThru -WindowStyle Hidden
 $taskUi.WaitForExit();$taskResult=Join-Path $PSScriptRoot 'test-v3-ui/results.json'
 if($taskUi.ExitCode -ne 0 -or -not(Test-Path $taskResult) -or -not(Get-Content -Raw $taskResult | ConvertFrom-Json).pass){throw "UI tests failed: $taskResult"}
 node (Join-Path $taskDesktop 'test-tray.cjs') (Join-Path $taskDist 'CursorMotion.exe') (Join-Path $taskStudio 'CursorMotion.Studio.exe')
 if($LASTEXITCODE -ne 0){throw 'Tray lifecycle tests failed'}
}
if(-not $OutputDirectory){
$taskShell=New-Object -ComObject WScript.Shell
$taskShortcut=$taskShell.CreateShortcut((Join-Path (Split-Path $PSScriptRoot -Parent) 'CursorMotion.lnk'))
$taskShortcut.TargetPath=Join-Path $taskDist 'CursorMotion.exe';$taskShortcut.Arguments='';$taskShortcut.WorkingDirectory=$taskDist
$taskShortcut.IconLocation=(Join-Path $taskDesktop 'ui/assets/AppIcon.ico')+',0';$taskShortcut.Save()
}
Write-Output "Ready: $taskDist"

